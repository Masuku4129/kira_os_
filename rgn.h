// Прямоугольные области: вычитание закрытых частей. Чистая геометрия без ядра (проверяется на хозяине).
// Композитор окон (wm.c) идёт от верхнего окна к нижнему и вычитает из области кадра то, что верхнее окно уже закрыло:
// нижние слои рисуются только там, где они видны, и каждая точка собирается один раз (docs/WM_PERF.md).
#ifndef RGN_H
#define RGN_H

typedef struct { int x0, y0, x1, y1; } rgn_rect_t;     // [x0,x1) x [y0,y1); пустой, если x1 <= x0 или y1 <= y0

#define RGN_MAX 32                                       // сколько прямоугольников в наборе (больше - вычитание не делается)

int rgn_intersect(const rgn_rect_t* a, const rgn_rect_t* b, rgn_rect_t* out);   // 1 - пересечение непусто (записано в out)
// Вычесть cover из каждого прямоугольника набора r[0..n). Части не пересекаются. Возвращает новое число прямоугольников.
// Если результат не поместился бы в cap (не больше RGN_MAX), набор остаётся прежним: рисовать лишнее безопасно, терять нужное нельзя.
int rgn_subtract(rgn_rect_t* r, int n, int cap, const rgn_rect_t* cover);

#endif
