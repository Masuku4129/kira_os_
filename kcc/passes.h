/* kcc: флаги отключения отдельных проходов оптимизации (-fno-xxx; для сверки с отключённым проходом и для поиска ошибок).
 * Определены в opt.c; разбор командной строки - kcc_flag. */
#ifndef KCC_PASSES_H
#define KCC_PASSES_H
extern int kcc_noregs;                        /* -fno-regs: пул из 8 регистров, все аргументы через домашнюю область, всегда кадр, выбор жертвы по весу */
extern int kcc_nodce;                         /* -fno-dce: не удалять недостижимые инструкции и ветвления по константе */
extern int kcc_noalign;                       /* -fno-align: без выравнивания заголовков циклов на 16 байт */
extern int kcc_nonnshift;                     /* -fno-nnshift: арифметический сдвиг вправо 32-бит читает нормализованный операнд (как до расширения пропуска нормализации) */
extern int kcc_nomrot;                        /* -fno-mrot: поворот распознаётся только у значений с одним определением */
int kcc_flag(const char *arg);                /* 1, если arg - известный флаг этого списка (и он применён) */
#endif
