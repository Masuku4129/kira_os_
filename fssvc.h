#ifndef KIRA_FSSVC_H
#define KIRA_FSSVC_H
/* Файловая служба на портах: порт «kira.fs» (общий для всех доменов), сообщения - каркас CBOR v1 (userland/kframe.h).
   Кто просит, определяет ядро по номеру отправителя, который проставляет port_recv (не по тексту сообщения): права CAP_FS и песочница
   /data/<программа> те же, что у системного вызова SYS_FS (fsrv.c), а выполняет их тот же fsrv_execute.

   Сначала клиент приветствует службу: {"op":"hello"} с вложенным личным портом - туда будут приходить ответы (одна привязка на процесс).
   Потом запросы (имя - [A-Za-z0-9._-], до 40 знаков):
     read   {"name","off"?,"len"}   -> res: байты (до 48 КБ) и code = прочитано; или с вложенной памятью: данные ложатся в неё с начала, res нет
     write  {"name","data"}          -> code 0; или с вложенной памятью: {"name","len"} - данные берутся из неё (файл заменяется целиком, до fsrv_max_data)
     stat   {"name"}                 -> code = размер файла
     list   {"len"?}                 -> res: имена через \n, code = байт
     remove {"name"}                 -> code 0
   code < 0 - ошибка: коды fsrv.h/kfs.h, FS_E_DENIED без права CAP_FS, FS_E_ARG на неверные аргументы; -200 - разбор сообщения (KF_E_*). */
void fssvc_init(void);   /* создаёт порт; вызывается один раз после монтирования ФС */
void fssvc_poll(void);   /* основной цикл ядра: обрабатывает ожидающие запросы (немного за раз) */
#endif
