#ifndef SMP_H
#define SMP_H

#include <stdint.h>
#include "cpumask.h"
#include "acpi.h"

// Запуск остальных процессоров (INIT-SIPI-SIPI), проверка межъядерных прерываний.
// После запуска каждое ядро входит в планировщик (v21c): у него свой холостой поток и свой тик LAPIC.
// Потоки идут на ядро только по маске (sched_create_on); остальные остаются на загрузочном ядре.
#define SMP_TRAMP_BASE   0x8000u        /* страница ниже 1 МБ для трамплина; вектор SIPI = база >> 12 */
#define SMP_AP_STACK     16384

// Команды ICR (xAPIC): режим доставки в битах 8-10, 14 = assert, 15 = по уровню.
#define ICR_INIT_ASSERT    0xC500u
#define ICR_INIT_DEASSERT  0x8500u
#define ICR_SIPI(vec)      (0x4600u | ((vec) & 0xFFu))
#define ICR_FIXED(vec)     (0x4000u | ((vec) & 0xFFu))
#define ICR_NMI_ALL_BUT_SELF 0xC4400u   /* сокращение «все, кроме себя» (биты 18-19 = 11), режим NMI */

// Чистая функция: из списка APIC ID (MADT) выбирает те, что надо запускать: без загрузочного процессора,
// без повторов, не больше max. Возвращает число выбранных.
unsigned smp_plan(const uint32_t* ids, unsigned n, uint32_t bsp_apic_id, uint32_t* out, unsigned max);

// Запускает процессоры из MADT. Возвращает число запущенных (без загрузочного). Требует кучу, APIC и часы TSC.
// TLB shootdown: request generation + per-CPU ack; при задержке >200 мс только предупреждение, не ранний возврат.
// Если CPU не ответил, блокировка запроса удерживается и backing memory не может быть переиспользована.
unsigned smp_start(const acpi_info_t* acpi);
unsigned smp_online(void);              /* включая загрузочный */
void smp_describe(void (*out)(const char*));
void ipi_dispatch(uint64_t vector, uint64_t cs);     /* из interrupts.s */

// Авария всей системы: останавливает остальные ядра (NMI). Если другое ядро уже делает то же, это ядро молча
// останавливается и не возвращается. smp_halting() - идёт ли остановка (NMI на остановленном ядре не печатает дамп).
void smp_halt_others(void);
int smp_halting(void);
// Просит простаивающее ядро, которому разрешено исполнять поток с маской affinity, выбрать поток заново:
// будит его межъядерным прерыванием, не дожидаясь тика. Вызывается при появлении готового потока.
void smp_kick_idle(cpumask_t affinity);
void smp_resched_cpu(unsigned cpu);     // ядру cpu пора выбрать поток заново (в его очереди более важная работа)

// Простой без тика. Холостое ядро выключает свой таймер LAPIC и спит до межъядерного прерывания (его посылают, когда
// появляется готовый поток). Тикает всегда одно ядро - хранитель времени: оно ведёт общее время, будит спящих,
// проверяет watchdog. Простаивающие ядра не просыпаются 500 раз в секунду: в эмуляторе это освобождает процессор
// машины-хозяина для самого эмулятора (экран, диск), на железе - экономит энергию.
void smp_idle_tick_off(void);           /* из цикла холостого потока */
void smp_idle_tick_on(void);            /* планировщик: ядро уходит из простоя */
unsigned smp_timekeeper(void);
void smp_timekeeper_failed(unsigned failed_cpu);   /* отказ хранителя времени: роль переходит живому ядру */

// Рабочая нагрузка проверки многоядерности: детерминированная свёртка, результат известен заранее.
#define SMP_WORK_ITERS    6000000ULL
#define SMP_WORK_EXPECTED 0xAE1696CB3F1D1B5BULL
uint64_t smp_work_checksum(uint64_t iters);

// Запускает проверку: по рабочему потоку на каждое запущенное ядро (плюс второй на первом - проверка вытеснения),
// каждый считает свёртку, спорит за замок и счётчик. Возвращает сразу; итог печатает последний рабочий поток.
// 0 - запущено, отрицательное - нельзя (нет ядер, нет тика LAPIC, уже идёт).
int smp_selftest_start(void);

// Проверка изоляции сбоев. mode 0 - ошибка в потоке ядра (гибнет поток, всё живо); 1 - отказ ядра cpu (машинная
// проверка: ядро выходит из работы); 2 - сбой под спин-замком (изолировать нельзя: авария системы с причиной).
// 0 - поток запущен, <0 - нельзя.
int smp_crash_test(unsigned mode, unsigned cpu);

#endif
