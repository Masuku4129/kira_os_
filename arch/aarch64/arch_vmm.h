#ifndef ARCH_VMM_H
#define ARCH_VMM_H
/* ARM64: нижняя половина TTBR0 (L0[0..255], до 128 ТБ) - тождественная карта ядра (ОЗУ и устройства), программам -
   верхняя (L0[256..511]): раскладка та же, что на x86-64, со сдвигом на 128 ТБ. */
#define VMM_USER_SHIFT 0x0000800000000000ULL
#define USER_VA(x) ((uint64_t)(x) + VMM_USER_SHIFT)   /* адрес раскладки программы для этой архитектуры */
#define USER_THREAD_SP(top) (top)         /* sp кратен 16, адрес возврата - в регистре, не на стеке */
#endif
