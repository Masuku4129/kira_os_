#ifndef WX_ARM_H
#define WX_ARM_H
// W^X для таблиц страниц ядра ARM64 (4-КБ гранула, 48 бит): права образа ядра постранично, остальная карта без исполнения,
// обход таблиц с поиском отображений "запись + исполнение". Логика без обращений к железу (таблицы и выдача страниц - через
// wx_env_t), поэтому проверяется хост-тестом tests/wx_arm_test.c. Типы wx_env_t, wx_layout_t, wx_stats_t - из wx.h
// (поля exec_lo/exec_hi на ARM64 не используются: lo == hi).
#include "wx.h"

// Применяет политику к таблицам с корнем l0 (тождественная карта и всё, что уже отображено): каждая запись получает PXN и
// UXN; блоки 1 ГБ и 2 МБ под образом дробятся до страниц 4 КБ, страницы образа получают права по layout
// (текст: RO, исполнение ядром; чтение: RO, PXN; данные: RW, PXN). Вызывать при выключенном MMU или с последующим сбросом TLB.
// 0 - успех; -1 - нет памяти под таблицу или страница образа лежит не в обычной памяти (атрибут MAIR не 2).
int wxa_enforce(const wx_env_t* env, uint64_t* l0, const wx_layout_t* l);

// Обходит все таблицы, считает отображённое (только обычная память) и ищет записываемое и исполняемое одновременно
// (EL1: AP[2]=0 и PXN=0; EL0: AP=01 и UXN=0). Ограничения на уровне таблиц (APTable, PXNTable) не учитываются:
// ядро их не ставит, а учёт в худшую сторону может лишь дать ложную тревогу. 0 - нарушений нет и образ отображён по layout.
int wxa_scan(const wx_env_t* env, const uint64_t* l0, const wx_layout_t* l, wx_stats_t* st);

#endif
