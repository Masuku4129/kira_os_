#ifndef EARLYMAP_H
#define EARLYMAP_H
// Ранняя карта страниц образа ядра (x86-64): identity-карта первого гигабайта, в которой образ с первой же
// инструкции после включения страничной адресации лежит БЕЗ страниц W+X: текст - RX, константы - R+NX,
// данные/bss/стеки - RW+NX, остальная память - RW+NX (исполняется только страница трамплина AP и, на время
// перехода при KASLR, одна страница "моста"). 2-МБ области, где есть что-то особое, дробятся на 4-КБ страницы.
//
// Логика не зависит от железа (доступ к таблицам - через wx_env_t.ptr), поэтому проверяется хост-тестом
// tests/earlymap_test.c через wx_scan. Первую карту до входа в C строит boot.s (то же правило, на ассемблере: у него
// нет ни стека, ни компилятора); эта функция строит карту для перемещённого образа (kaslr_arch.c).
#include <stdint.h>
#include "wx.h"

#define EARLYMAP_LIMIT (1ULL << 30)             // identity-карта: первый гигабайт, как в boot.s
#define EARLYMAP_PT_MAX 10                      // страниц таблиц в пуле boot.s (early_pt_pool); образ до 16 МБ + низкая область + мост

// Физические адреса таблиц (identity: они же адреса для доступа - через env->ptr) и пул страниц для 4-КБ таблиц.
typedef struct {
    uint64_t pml4, pdpt, pd;                    // по одной странице
    uint64_t pt_pool;                           // pt_pool_n страниц подряд
    unsigned pt_pool_n;
} earlymap_pa_t;

typedef struct {
    wx_layout_t w;                              // секции образа и страница трамплина AP (exec_lo/hi)
    uint64_t image_lo, image_hi;                // весь образ (с bss); границы кратны 4096
    uint64_t exec2_lo, exec2_hi;                // ещё одна исполняемая страница (мост KASLR); lo == hi - нет
} earlymap_layout_t;

// Строит карту с нуля. 0 - успех; -1 - границы не выровнены или образ выше предела карты; -2 - не хватило пула.
int earlymap_build(const wx_env_t* env, const earlymap_pa_t* pa, const earlymap_layout_t* l);

// Делает 4-КБ страницу va данными (RW+NX, адрес и прочие биты сохраняются): так закрывается мост после перехода.
// 0 - готово, -1 - страницы нет или она не 4-КБ (отображение этого адреса не трогается).
int earlymap_make_data(const wx_env_t* env, uint64_t pml4_pa, uint64_t va);

#endif
