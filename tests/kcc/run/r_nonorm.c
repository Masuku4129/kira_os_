/* Пропуск нормализации 32-битных результатов: значения без переполнения знакового int (его поведение не определено): там, где значение читают только 32-битные операции,
 * а где нужна каноническая форма (сравнение, индекс, расширение, деление, сдвиг вправо) - нормализация остаётся. Счётчики циклов - обычные (без переполнения). */
static int G[8];
static unsigned char U8[64];
int main(void) {
    long acc = 0;
    unsigned h = 17u;
    int s = 0, t = 1;
    for (int i = 0; i < 1000; i++) {
        s += i * 40;                     /* сумма и произведение, читаются только сложением и записью */
        t = (t * 3 + i) & 0xffff;
        G[i & 7] = s ^ t;               /* store.4 */
        h = h * 31u + (unsigned)(s >> 3);
    }
    acc += G[0] + G[3] + G[7];
    acc += s;                           /* расширение до 64 бит после цепочки без нормализации */
    acc ^= (long)t;
    int w = 1000000000;
    w = w + w;                          /* без переполнения: 2e9 помещается в int */
    acc += (long)(unsigned)w;
    int x = 40000;
    int y = x * x;                      /* то же */
    acc += (long)(unsigned)y;
    int q = 0;
    for (int i = 0; i < 64; i++) { q += i * i; U8[i] = (unsigned char)q; }
    acc += U8[10] + U8[33] + U8[63];
    int cnt = 0;
    for (int i = -5; i < 30; i += 3) { cnt += i; acc += (long)i * 1000; }
    acc += cnt;
    unsigned u = 4000000000u;
    u = u + u + 5u;                     /* беззнаковое переполнение определено */
    acc += (long)u;
    int m = 7, d = 3;
    acc += (m * 5 + 1) / d + (m - 20) % d;       /* деление требует канонической формы */
    int sh = -64;
    acc += (sh + 16) >> 2;                       /* арифметический сдвиг вправо */
    return (int)((acc ^ (long)h) & 0xffffff);
}
