// Регулятор темпа кадров компоновщика. Чистая логика без ядра: раз в секунду получает число кадров и опоздавших кадров
// цикла дисплея и решает (1) темп фоновых окон, (2) уровень анимации фона. Разум в этом не участвует: решение
// детерминированное, без обучения, одинаковое на любом образе.
#ifndef FRAMEGOV_H
#define FRAMEGOV_H
#include <stdint.h>

#define FGOV_FX_AUTO 4          // значение настройки анимации «решает регулятор»

typedef struct {
    uint32_t lvl, calm, bad, fxcalm;    // ступень темпа, спокойные секунды, плохие секунды, спокойные секунды анимации
    uint32_t fx;                         // текущий уровень анимации 0..3
    uint32_t bg_fps;                     // темп фоновых окон сейчас, кадров/с (0 - без предела)
} framegov_t;

void framegov_init(framegov_t* g);
// frames, late - кадров и опоздавших за последнюю секунду; fx_setting: 0..3 вручную или FGOV_FX_AUTO.
// Возвращает 1, если темп фоновых окон сменился (g->bg_fps - новое значение).
int framegov_second(framegov_t* g, uint32_t frames, uint32_t late, int fx_setting);

#endif
