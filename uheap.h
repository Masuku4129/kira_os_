#ifndef UHEAP_H
#define UHEAP_H

#include <stdint.h>
#include "arch_vmm.h"

/* Куча программы Ring 3: растёт только вверх от UHEAP_VA страницами по 4 КБ, память нулевая, RW-NX.
   Системный вызов SYS_HEAP(pages) возвращает адрес начала НОВОГО куска; куски идут подряд, так что
   программа видит один непрерывный массив. Память возвращается ядру при завершении процесса.

   Пределы зависят от машины, а не от константы: одна программа может занять не больше половины всей ОЗУ,
   а ядру всегда остаётся запас (1/16 ОЗУ, не меньше 4 МБ). Окно адресов ограничено первой пользовательской
   записью PML4 (до 1 ТБ). Какой программе сколько - решение политики прав (организм), здесь только жёсткие границы. */
#define UHEAP_VA          USER_VA(0x0000008200000000ULL)
#define UHEAP_VA_END      USER_VA(0x0000010000000000ULL)
#define UHEAP_MIN_QUOTA   256u                   /* страниц: даже на самой маленькой машине программе положен 1 МБ */
#define UHEAP_MIN_RESERVE_KB 4096u

enum { UHEAP_OK = 0, UHEAP_E_ARG = -1, UHEAP_E_QUOTA = -2, UHEAP_E_MEM = -3 };

/* Предел кучи одной программы в страницах для машины с total_kb ОЗУ. */
uint64_t uheap_quota_pages(uint64_t total_kb);
/* Сколько КБ свободной ОЗУ должно остаться после выдачи (ядру и другим программам). */
uint64_t uheap_reserve_kb(uint64_t total_kb);

/* Решает, можно ли выдать req страниц, если уже выдано cur. free_kb - свободная память ядра, total_kb - вся ОЗУ.
   Таблицы страниц тоже занимают память: по странице на каждые 512 страниц данных плюс запас на верхние уровни. */
int uheap_check(uint64_t cur_pages, uint64_t req_pages, uint64_t free_kb, uint64_t total_kb);

#endif
