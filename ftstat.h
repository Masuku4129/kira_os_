// Статистика времени кадра: среднее, 99-й процентиль и максимум по последним кадрам. Чистая логика без ядра (проверяется на хозяине).
// Нужна замеру плавности интерфейса (docs/WM_PERF.md): среднее скрывает редкие тяжёлые кадры, а глаз замечает именно их.
#ifndef FTSTAT_H
#define FTSTAT_H
#include <stdint.h>

#define FTS_N 1024                    // сколько последних кадров помнится (больше - старые вытесняются)

typedef struct { uint32_t us[FTS_N]; uint32_t n; uint32_t pos; uint64_t sum; uint64_t total; uint32_t max; } fts_t;   // n - сколько в окне, total - сколько всего после сброса

void     fts_reset(fts_t* f);
void     fts_push(fts_t* f, uint32_t us);       // время кадра в микросекундах
uint32_t fts_count(const fts_t* f);             // всего кадров после сброса
uint32_t fts_avg(const fts_t* f);               // по всем кадрам после сброса; 0, если кадров не было
uint32_t fts_max(const fts_t* f);               // максимум за всё время после сброса, а не только по окну в FTS_N кадров
uint32_t fts_p99(const fts_t* f);               // по окну последних FTS_N кадров: значение, которого не превышают 99% кадров (метод «ближайший ранг»)

#endif
