#ifndef KIRA_TRUSTANCHOR_H
#define KIRA_TRUSTANCHOR_H
/* Опора защиты от отката в TPM (А3): склеивает чистую политику (rollback.h), команды NV (tpm2.h), драйвер TIS (tpmtis.h), сведения загрузчика
   (boottrust.h) и том KiraFS (kfs.h). Две задачи.
   1. Счётчик выпуска. Загрузчик сверил выпуск с монотонным счётчиком TPM и допустил загрузку; здесь счётчик поднимается до номера выпуска -
      но только после подтверждённой «хорошей» загрузки: система проработала TRUSTANCHOR_GOOD_BOOT_S секунд, дошла до главного цикла, не было паники.
   2. Якорь эпохи диска. Эпоха тома (kfs_epoch) периодически и при выключении закрепляется в ячейке TPM. При монтировании эпоха сверяется с якорем:
      меньше - подставлена старая копия диска; том переводится в безопасный режим (только чтение) до подтверждения оператором (fsanchor accept).
   Без TPM (или на архитектуре без драйвера) ничего из этого не работает, и ядро говорит об этом строкой в журнале: молчаливой защиты нет. */
#include <stdint.h>

#define TRUSTANCHOR_GOOD_BOOT_S   20u     /* секунд работы без сбоя до подъёма счётчика выпуска */
#define TRUSTANCHOR_ANCHOR_EVERY_S 900u   /* не чаще раза в 15 минут: каждая запись якоря изнашивает NV-память TPM */

void trustanchor_init(void);              /* после boottrust_init: опрос TPM, строки [KIRA BOOT] rollback: ... */
void trustanchor_fs_mounted(void);        /* сразу после kfs_mount: сверка эпохи с якорем, при откате - безопасный режим */
void trustanchor_tick(void);              /* из главного цикла: подтверждение хорошей загрузки и периодическое закрепление эпохи */
void trustanchor_shutdown(void);          /* перед выключением и перезагрузкой: эпоха и якорь на носитель */
void trustanchor_command(const char* arg);/* команда fsanchor: status | sync | accept */
#endif
