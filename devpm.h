#ifndef KIRA_DEVPM_H
#define KIRA_DEVPM_H
/* Реестр хуков сна и пробуждения устройств (сон S3 по ACPI). Уровень 2: драйверы регистрируют свои хуки при запуске,
   оркестратор сна (sleep.c) вызывает их все разом. Чистый код без железа: проверяется на хосте (tests/devpm_test.c).

   Порядок. Хуки регистрируются в порядке запуска драйверов (раньше - то, от чего зависят остальные: конфигурация PCI, IOMMU, затем шины
   и устройства). Ко сну их вызывают в ОБРАТНОМ порядке (сначала то, что поднято последним), при пробуждении - в порядке регистрации.

   Договор suspend: устройство перестаёт обращаться к памяти (DMA) и выдавать прерывания; всё, что нужно для возврата, запоминается.
   Возврат 0 - готово; < 0 - устройство НЕ переживёт сон (нечем сохранить состояние, занято): сон отменяется, уже усыплённые устройства
   возвращаются в работу, причина (имя устройства и код) идёт в журнал "[KIRA SLEEP] ...". Молча сломанное устройство хуже отказа.
   Договор resume: устройство снова работает так, как до сна. < 0 - не восстановилось: об этом пишется в журнал, остальные продолжают. */
#include <stdint.h>

#define DEVPM_MAX 64

typedef int (*devpm_fn)(void* ctx);

/* Хук регистрируется один раз; повторная регистрация того же имени заменяет прежнюю (драйвер перезапущен). 0 - принят, -1 - реестр полон / нет имени. */
int devpm_register(const char* name, devpm_fn suspend, devpm_fn resume, void* ctx);
int devpm_count(void);

/* Журнал: строки без перевода строки в конце. По умолчанию молчит (в ядре его ставит sleep.c). */
void devpm_set_log(void (*fn)(const char*));

/* Усыпить все: 0 - все готовы; < 0 - отказ (devpm_refusal() - имя, devpm_refusal_code() - код); откат уже сделан. */
int devpm_suspend_all(void);
/* Разбудить усыплённых; возвращает число хуков, у которых resume вернул ошибку (0 - всё восстановлено). */
int devpm_resume_all(void);

const char* devpm_refusal(void);
int devpm_refusal_code(void);

typedef struct { const char* name; int state; int last_rc; } devpm_info_t;   /* state: 0 - работает, 1 - усыплено, 2 - не восстановилось */
int devpm_info(int i, devpm_info_t* out);   /* 0 - есть такой хук */

#endif
