#!/usr/bin/env python3
"""Validate a KDRV publisher-key manifest and generate the kernel trust table.

The manifest contains public material only. Private Ed25519 keys are never read,
created, or written by this tool. Updating the trust table is a source/release
change and therefore requires the normal KIRA OS release authorization path.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

KEY_ID_RE = re.compile(r"^[A-Za-z0-9._-]{16}$")
MAX_KEYS = 32


def load_manifest(path: Path) -> list[dict]:
    obj = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(obj, dict) or obj.get("format") != 1:
        raise ValueError("manifest must be an object with format: 1")
    rows = obj.get("keys")
    if not isinstance(rows, list) or not 1 <= len(rows) <= MAX_KEYS:
        raise ValueError(f"keys must contain 1..{MAX_KEYS} entries")
    seen: set[str] = set()
    active = 0
    out = []
    for n, row in enumerate(rows):
        if not isinstance(row, dict):
            raise ValueError(f"keys[{n}] must be an object")
        key_id = row.get("id")
        public_hex = row.get("public_key")
        revoked = row.get("revoked", False)
        if not isinstance(key_id, str) or not KEY_ID_RE.fullmatch(key_id):
            raise ValueError(f"keys[{n}].id must be exactly 16 safe ASCII characters")
        if key_id in seen:
            raise ValueError(f"duplicate publisher key id: {key_id}")
        seen.add(key_id)
        if not isinstance(public_hex, str) or not re.fullmatch(r"[0-9a-fA-F]{64}", public_hex):
            raise ValueError(f"keys[{n}].public_key must be 32 bytes encoded as 64 hex characters")
        public = bytes.fromhex(public_hex)
        if not any(public):
            raise ValueError(f"keys[{n}].public_key cannot be all zero")
        if not isinstance(revoked, bool):
            raise ValueError(f"keys[{n}].revoked must be boolean")
        if not revoked:
            active += 1
        out.append((key_id, public, revoked))
    if not active:
        raise ValueError("trust manifest must retain at least one active key")
    return out


def render(keys: list[tuple[str, bytes, bool]]) -> str:
    primary = next((key_id for key_id, _, revoked in keys if not revoked), keys[0][0])
    lines = [
        "#ifndef KIRA_KDRV_TRUST_H",
        "#define KIRA_KDRV_TRUST_H",
        "/* Generated by tools/kdrvtrust.py from a reviewed public-key manifest.",
        "   Contains public keys only; never place private signing keys in this file. */",
        '#include "kdrv_sig.h"',
        "",
        f'#define KDRV_TRUST_KEY_ID "{primary}"',
        "static const kdrv_sig_key_t kdrv_trust_keys[] = {",
    ]
    for key_id, public, revoked in keys:
        octets = ",".join(f"0x{x:02x}" for x in public)
        flags = "KDRV_SIG_KEY_REVOKED" if revoked else "0"
        lines.extend([
            "    {",
            f'        "{key_id}",',
            f"        {{ {octets} }},",
            f"        {flags}",
            "    }},",
        ])
    lines.extend([
        "};",
        "#define KDRV_TRUST_KEY_COUNT ((uint32_t)(sizeof kdrv_trust_keys / sizeof kdrv_trust_keys[0]))",
        "",
        "#endif",
        "",
    ])
    return "\n".join(lines)


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".kdrvtrust-", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
        dirfd = os.open(str(path.parent), os.O_RDONLY)
        try:
            os.fsync(dirfd)
        finally:
            os.close(dirfd)
    except Exception:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("manifest", type=Path, help="reviewed JSON manifest containing public keys")
    ap.add_argument("--output", type=Path, required=True, help="generated kdrv_trust.h")
    ap.add_argument("--check", action="store_true", help="fail if output differs; do not write")
    args = ap.parse_args()
    keys = load_manifest(args.manifest)
    result = render(keys)
    if args.check:
        try:
            existing = args.output.read_text(encoding="utf-8")
        except OSError as exc:
            raise ValueError(f"cannot read generated header: {exc}") from exc
        if existing != result:
            print("KDRV trust header is stale; regenerate it from the reviewed manifest", file=sys.stderr)
            return 1
    else:
        atomic_write(args.output, result)
    print(f"KDRV trust table: {len(keys)} public keys, {sum(not revoked for _, _, revoked in keys)} active")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"kdrvtrust: {exc}", file=sys.stderr)
        raise SystemExit(2)
