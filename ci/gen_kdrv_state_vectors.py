#!/usr/bin/env python3
"""Regenerates tests/kdrv_state_vectors.h: test packages (kdrv_header_t + payload) signed by the real tools/kdrvsign.py
with two RFC 8032 test keys. Ed25519 is deterministic, so the output is reproducible:
    python3 ci/gen_kdrv_state_vectors.py > tests/kdrv_state_vectors.h
"""
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, NoEncryption, PrivateFormat, PublicFormat

ROOT = Path(__file__).resolve().parents[1]
KEYS = {
    "A": ("TEST-ED25519-001", "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60"),
    "B": ("TEST-ED25519-002", "4ccd089b28ff96da9db6c346ec114e0f5b8a319f35aba624da8cf6ed4fb8a6fb"),
}
NOT_BEFORE, NOT_AFTER = 1700000000, 1800000000


def package(version: int) -> bytes:
    payload = b"KIRA test driver payload v%d" % version
    match = struct.pack("<HHII", 0x1234, 0x11E8, 0, 0) + b"\0" * (12 * 7)
    header = struct.pack("<IHH16sIIII", 0x5652444B, 1, 136, b"tdrv", version, 0, len(payload), 1) + match
    assert len(header) == 136
    return header + payload


def c_array(name: str, data: bytes) -> str:
    rows = ",\n".join("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12))
    return f"static const uint8_t {name}[{len(data)}] = {{\n{rows}\n}};\n"


def main() -> int:
    out = ["/* Generated by ci/gen_kdrv_state_vectors.py - do not edit. Test keys only (RFC 8032), never trusted by the kernel. */\n"]
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        keyfiles = dict()
        for tag, (key_id, seed) in KEYS.items():
            priv = Ed25519PrivateKey.from_private_bytes(bytes.fromhex(seed))
            pub = priv.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
            pem, hexf, trust = root / f"{tag}.pem", root / f"{tag}.hex", root / f"{tag}.h"
            pem.write_bytes(priv.private_bytes(Encoding.PEM, PrivateFormat.PKCS8, NoEncryption()))
            hexf.write_text(pub.hex() + "\n")
            trust.write_text(f'#define KDRV_TRUST_KEY_ID "{key_id}"\n' + ",".join(f"0x{b:02x}" for b in pub) + "\n")
            keyfiles[tag] = (pem, hexf, trust, key_id)
            out.append(c_array(f"vec_pub_{tag}", pub))

        def sign(pkg_name: str, data: bytes, tag: str) -> bytes:
            pem, hexf, trust, key_id = keyfiles[tag]
            pkg_path, sig_path = root / f"{pkg_name}.kdrv", root / f"{pkg_name}_{tag}.sig"
            pkg_path.write_bytes(data)
            subprocess.run([sys.executable, str(ROOT / "tools" / "kdrvsign.py"), str(pkg_path), "--key", str(pem),
                            "--public-key", str(hexf), "--trust-header", str(trust), "--key-id", key_id,
                            "--not-before", str(NOT_BEFORE), "--not-after", str(NOT_AFTER), "--output", str(sig_path)],
                           check=True, capture_output=True)
            return sig_path.read_bytes()

        for version in (4, 5, 6, 7):
            data = package(version)
            out.append(c_array(f"vec_pkg_v{version}", data))
            out.append(c_array(f"vec_sig_v{version}_A", sign(f"v{version}", data, "A")))
        out.append(c_array("vec_sig_v6_B", sign("v6", package(6), "B")))
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
