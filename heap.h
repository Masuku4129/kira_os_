#ifndef HEAP_H
#define HEAP_H

#include <stdint.h>
#include <stddef.h>

// Куча ядра. Память берётся у менеджера страниц по мере надобности и возвращается ему, поэтому предел кучи -
// вся ОЗУ машины, а не заранее отведённый кусок.
//  - Мелкие блоки (до HEAP_SLAB_MAX байт): классы размеров 16..2016, страница-«плита» на класс, занятость - битовая карта
//    в заголовке страницы. Выделение и освобождение не зависят от числа блоков в куче.
//  - Крупные: целые страницы подряд, адрес выровнен по странице.
// Каждая страница кучи записана в таблице владения: kfree проверяет, что адрес выдан кучей и ещё не освобождён
// (чужой указатель и повторное освобождение отвергаются с сообщением, куча не портится).
// Выравнивание: не меньше 16 байт (крупные блоки - 4096).
#define HEAP_SLAB_MAX 2016

typedef struct {
    size_t   used_bytes;      // выдано (по размеру класса / целым страницам)
    unsigned used_blocks;     // живых блоков
    unsigned slab_pages;      // страниц под мелкие блоки
    unsigned large_pages;     // страниц под крупные блоки
    size_t   slab_free_bytes; // свободно внутри страниц мелких блоков
    unsigned bad_frees;       // отвергнутые освобождения (чужой адрес, повтор)
} heap_stats_t;

void heap_init(void);
void heap_get_stats(heap_stats_t* out);
void* kmalloc(size_t size);
void kfree(void* ptr);
void* krealloc(void* ptr, size_t size);
size_t kmalloc_usable(const void* ptr);
unsigned heap_trim(void);                 // вернуть менеджеру страниц запасные пустые плиты (нехватка памяти); сколько страниц   // сколько байт реально доступно в блоке (0 - не блок кучи)

#endif
