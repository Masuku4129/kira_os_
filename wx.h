#ifndef WX_H
#define WX_H
// W^X для страниц ядра x86-64: приведение таблиц страниц к политике "ни одна страница не записываема и исполняема
// одновременно" и обход таблиц для проверки. Логика не зависит от железа (доступ к таблицам и выдача страниц - через
// wx_env_t), поэтому проверяется хост-тестом tests/wx_test.c на искусственных таблицах.
#include <stdint.h>

#define WX_P  (1ULL << 0)
#define WX_W  (1ULL << 1)
#define WX_PS (1ULL << 7)
#define WX_NX (1ULL << 63)

typedef struct {
    uint64_t* (*ptr)(uint64_t phys);       // таблица по физическому адресу
    uint64_t  (*alloc)(void);              // страница под новую таблицу (физический адрес, 4 КБ, любое содержимое), 0 - нет памяти
} wx_env_t;

// Все границы кратны 4096; диапазоны [lo, hi) не пересекаются. Адреса виртуальные = физические (identity-карта в PML4[0]).
typedef struct {
    uint64_t text_lo, text_hi;             // код ядра: RX
    uint64_t ro_lo, ro_hi;                 // константы: R, NX
    uint64_t data_lo, data_hi;             // данные, bss, стеки: RW, NX
    uint64_t exec_lo, exec_hi;             // дополнительная страница кода вне образа (трамплин AP): RX; lo == hi - нет
} wx_layout_t;

typedef struct {
    uint64_t exec_kb;                      // отображено исполняемого (и не записываемого)
    uint64_t ro_kb;                        // отображено только для чтения, без исполнения
    uint64_t rw_kb;                        // отображено записываемого, без исполнения
    uint64_t bad_count;                    // страниц (листьев) с W+X
    uint64_t bad_va;                       // первый адрес с нарушением (для сообщения)
    int      layout_ok;                    // образ ядра отображён с ожидаемыми правами
    uint64_t layout_bad_va;                // первая страница образа с неверными правами
} wx_stats_t;

// Применяет политику к identity-карте (PML4[0]): листья вне образа получают NX, 2-МБ страницы под образом и
// трамплином дробятся на 4-КБ, права страниц образа ставятся по layout. 0 - успех, -1 - нет памяти или
// неподдерживаемая запись (1-ГБ лист или бит PAT у 2-МБ страницы под образом). Вызывающий сбрасывает TLB.
int wx_enforce(const wx_env_t* env, uint64_t* pml4, const wx_layout_t* l);

// Обходит все таблицы от pml4 (все 512 записей), считает отображённое по классам и ищет W+X (эффективные права:
// запись - если разрешена на всех уровнях, запрет исполнения - если задан на любом). 0 - нарушений нет и образ
// отображён по layout, -1 - иначе (подробности в st).
int wx_scan(const wx_env_t* env, const uint64_t* pml4, const wx_layout_t* l, wx_stats_t* st);

#endif
