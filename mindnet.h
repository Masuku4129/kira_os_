#ifndef MINDNET_H
#define MINDNET_H

#include <stdint.h>

/* Модель предвидения Разума (стратегический уровень): логистическая регрессия с обучением на ходу.
   Каждую секунду по замерам системы (признаки 0..1 в формате Q16) предсказывается вероятность того, что в следующую
   секунду экран будет опаздывать; через секунду ответ становится известен, и веса сдвигаются по ошибке (градиентный
   спуск по логарифмической потере). Веса - числа этой машины: они хранятся на диске вместе с остальным опытом.
   Целочисленная арифметика (ядро собрано без SSE), сигмоида - по таблице. Чистый модуль: проверяется на хосте. */

#define MNET_F   12                 /* признаков */
#define MNET_ONE 65536              /* 1.0 в Q16 */

typedef struct {
    int32_t  w[MNET_F];             /* веса, Q16 */
    int32_t  b;                     /* смещение, Q16 */
    uint32_t n;                     /* обучающих примеров за жизнь */
    uint32_t pos;                   /* из них «экран опаздывал» */
    /* качество за последние ~5 минут (счётчики затухают): предсказано/случилось */
    uint32_t tp, fp, fn, tn;        /* x16 (затухание 1/256 на шаг) */
    uint32_t loss_x1e4;             /* средняя логарифмическая потеря x1e4 (EWMA) */
} mnet_t;

void     mnet_init(mnet_t* m);
uint32_t mnet_sigmoid(int32_t z);                         /* z в Q16 -> вероятность в Q16 */
uint32_t mnet_predict(const mnet_t* m, const int32_t* x); /* вероятность, Q16 */
/* Один шаг обучения: пример x с исходом y (0/1); p - вероятность, которую модель дала для x до шага. */
void     mnet_train(mnet_t* m, const int32_t* x, int y);
/* Признак с наибольшим вкладом в «опоздание» для x (для объяснения решения); -1 - таких нет. */
int      mnet_top_feature(const mnet_t* m, const int32_t* x);
/* Зрелость: модель видела достаточно и её предупреждения сбывались (точность >= 1/2, есть попадания). */
int      mnet_trusted(const mnet_t* m);
/* Точность и полнота предупреждений, % (по затухающим счётчикам; 0, если не из чего считать). */
unsigned mnet_precision(const mnet_t* m);
unsigned mnet_recall(const mnet_t* m);

#endif
