#ifndef KIRA_CAPS_H
#define KIRA_CAPS_H
/* Права (capabilities) программ Ring 3 / EL0. Набор прав процесса задаётся при запуске по имени доверенной программы
   (манифест сборки с SHA-256 подтверждает, что это та самая программа) и не меняется до конца её жизни. Вызов без права
   получает отказ KE_PERM (для файлов - FS_E_DENIED), событие записывается в журнал один раз на процесс.
   Без проверки права доступны только вызовы, не затрагивающие ничего вне процесса: write (в журнал процесса), exit, часы, sleep,
   yield, куча, фьютексы, аргументы, случайные числа, закрытие своих дескрипторов. */
#include <stdint.h>
enum {
    CAP_GFX       = 1u << 0,    /* окно: создать, показать, события ввода */
    CAP_NET       = 1u << 1,    /* DNS и исходящие TCP-соединения */
    CAP_NET_SERVE = 1u << 2,    /* слушать порт TCP и принимать соединения */
    CAP_UDP       = 1u << 3,    /* сокеты UDP */
    CAP_SND       = 1u << 4,    /* воспроизведение и громкость своего потока */
    CAP_REC       = 1u << 5,    /* запись с микрофона / линейного входа */
    CAP_IPC       = 1u << 6,    /* именованные порты и общая память */
    CAP_THREAD    = 1u << 7,    /* создание потоков */
    CAP_FS        = 1u << 8,    /* своя песочница /data/<имя> */
    CAP_GRANT     = 1u << 9,    /* чтение одного файла, выданного при запуске (Проводник -> просмотр) */
    CAP_SYSFILES  = 1u << 10,   /* общие файлы системы только для чтения (/etc/ssl) */
    /* Права драйверов Ring 3 (kdrv_format.h, docs/DRIVERS.md): даются только процессу drv-ИМЯ, запущенному менеджером драйверов
       по пакету /drv/ИМЯ.kdrv с подтверждением в /drv/ИМЯ.rec; действуют только на ЕГО устройство PCI. */
    CAP_MMIO      = 1u << 11,   /* отобразить область BAR своего устройства (без кэша, без исполнения) */
    CAP_IRQ       = 1u << 12,   /* ждать прерывание своего устройства (MSI / MSI-X) */
    CAP_DMA       = 1u << 13,   /* непрерывная память для DMA устройства */
    CAP_PCIDEV    = 1u << 14,   /* конфигурационное пространство своего устройства */
    CAP_NETDEV    = 1u << 15,   /* отдать сетевому стеку ядра карту с кольцами в общей памяти */
    CAP_JIT       = 1u << 16,   /* окно кода JIT: выдать страницы RW-NX и один раз запечатать их RX (никогда W+X вместе); только интерпретатор wasm */
    CAP_ALL_      = (1u << 17) - 1,
    CAP_DRIVER_   = CAP_MMIO | CAP_IRQ | CAP_DMA | CAP_PCIDEV | CAP_NETDEV
};
uint32_t    caps_for_program(const char* name);     /* права доверенной программы; неизвестное имя - 0 */
const char* caps_bit_name(uint32_t bit);            /* "CAP_NET" и т.д. для журнала */
#endif
