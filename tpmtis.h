#ifndef KIRA_TPMTIS_H
#define KIRA_TPMTIS_H
/* Драйвер TPM 2.0 по интерфейсу TIS (FIFO через память, адрес 0xFED40000, локальность 0): передача команды и приём ответа. Нужен ядру для двух
   вещей (А3): подтверждение «хорошей» загрузки (подъём счётчика выпуска) и якорь эпохи диска. Команды собирает tpm2.c; здесь только перенос
   байтов. Только x86-64: на других архитектурах TPM в ядро не подключён (docs/SECURE_BOOT.md). Прерываний драйвер не использует (опрос с
   предельным временем), поэтому работает и при выключении машины. */
#include <stdint.h>
#include <stddef.h>

/* 0 - устройство TIS есть и отвечает; -1 - нет. Повторные вызовы дёшевы. */
int tpmtis_probe(void);
/* Обмен: cmd -> rsp. *rsp_len на входе - размер буфера, на выходе - длина ответа. 0 - успех, -1 - нет устройства или тайм-аут. Под мьютексом. */
int tpmtis_submit(const uint8_t* cmd, size_t cmd_len, uint8_t* rsp, size_t* rsp_len);
#endif
