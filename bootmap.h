#ifndef BOOTMAP_H
#define BOOTMAP_H

#include <stdint.h>

// Раннее окно в физическую память за пределами identity-карты (первый 1 ГБ).
// Нужно до того, как работают PMM и VMM: через него читается Multiboot2-структура,
// если загрузчик (типично UEFI) положил её выше 1 ГБ, и рисуется раннее окно журнала
// на видеопамяти, лежащей выше 1 ГБ.
//
// Устройство: запись PML4[511] -> один статический PDPT -> один статический PD с 512
// страницами по 2 МБ. Окно занимает виртуальные адреса от BOOTMAP_BASE на 1 ГБ.
// Запись PML4[511] копируется в каждое адресное пространство процесса (vmm_space_create),
// поэтому окно видно и при активном CR3 процесса; бита USER в записях нет.
#define BOOTMAP_BASE  0xFFFFFF8000000000ULL
#define BOOTMAP_SLOT  (2ULL << 20)
#define BOOTMAP_SLOTS 512

int  bootmap_init(void);                       // 0 - окно установлено (или уже было); -1 - PML4[511] занята
// Отображает [phys, phys+len) страницами по 2 МБ. uncached=1 - для видеопамяти и MMIO.
// Возвращает виртуальный адрес, соответствующий phys, или 0 (нет места, переполнение, окно не установлено).
void* bootmap_map(uint64_t phys, uint64_t len, int uncached);
void  bootmap_release_all(void);               // снять все отображения окна (перед тем, как драйвер экрана отобразит видеопамять сам)
unsigned bootmap_used_slots(void);

#endif
