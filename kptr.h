#ifndef KPTR_H
#define KPTR_H
// Политика kptr: что журналы и консоль имеют право сказать об адресах образа ядра. KASLR прячет базу ядра; любой вывод
// "RIP = 0x...", адреса возврата или слова стека в журнале её тут же раскрыл бы тому, кто читает журнал или снимок экрана.
//   - Обычный режим: адреса ВНУТРИ образа ядра печатаются как "K+0xСМЕЩЕНИЕ" (смещение от начала образа: по карте
//     сборки с ним работать можно, базу оно не раскрывает). Прочие значения (порты, куча, физические адреса,
//     числа) печатаются как есть: они не выдают положения образа.
//   - Режим отладки (параметр командной строки ядра kira.debug или команда "kptr debug on"): печатаются настоящие адреса.
// Режим отладки по умолчанию ВЫКЛЮЧЕН.
#include <stdint.h>

int  kptr_debug(void);
void kptr_set_debug(int on);
int  kptr_in_image(uint64_t v);              // адрес внутри образа ядра [kernel_start, kernel_end)
void kptr_print(uint64_t v);                 // в журнал/на консоль по политике выше
// Хост-тест: то же решение без вывода. buf >= 24 байт; возвращает длину строки.
unsigned kptr_format(uint64_t v, uint64_t image_lo, uint64_t image_hi, int debug, char* buf);

#endif
