#ifndef KIRA_SLEEP_H
#define KIRA_SLEEP_H
/* Сон S3 (ACPI): оркестратор уровня 6. Порядок: отказ, если устройством владеет драйвер Ring 3 -> заморозка потоков процессов -> то же, что при штатном
   выключении (опыт Разума, чёрный ящик, отложенная запись ФС, кэши дисков) -> хуки устройств (devpm) -> заморозка остальных потоков ->
   platform_sleep (процессоры и машина; возвращается после пробуждения) -> хуки в обратном порядке -> разморозка. Устройство, которое сон не переживёт,
   не ломается молча: сон отменяется с причиной в журнале ("[KIRA SLEEP] ...") и система работает как работала. */
#include <stdint.h>

int  sleep_enter(const char* source);     /* source - кто просит (в журнал); 1 - спали и проснулись, 0 - сон не состоялся (причина в журнале) */
void sleep_request(void);                 /* отложенный запрос (кнопка сна, крышка): исполняет основной цикл ядра */
int  sleep_take_request(void);            /* 1 - запрос есть (снимается) */
void sleep_describe(void (*out)(const char*));   /* команда sleep status */
#endif
